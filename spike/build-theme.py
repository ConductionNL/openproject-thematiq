"""Generate theme.css for OpenProject from one token set.

usage: build-theme.py <design-systems.json> <system-id> <geometry.css> <out.css>

Part 1 (generated): token values mapped onto the CSS custom properties OpenProject 17.9 reads
(its own --header-*/--main-menu-*/--button--* layer and the Primer layer scoped on [data-color-mode]).
Part 2 (static, geometry.css): geometry overrides from the shell canon. Identical for every token set.
"""
import json
import sys

src, system, geometry, out = sys.argv[1:5]
entry = json.load(open(src))["systems"][system]
t = entry["vars"]
font = entry["font"]["family"]

v = lambda k: t["--sc-" + k]

root = {
    # OpenProject's own design variables (the ones the Enterprise "Design" page writes)
    "--header-bg-color": v("primary"),
    "--header-item-font-color": "#ffffff",
    "--header-item-font-hover-color": "#ffffff",
    "--header-item-bg-hover-color": v("primary-deep"),
    "--header-border-bottom-width": "0",
    "--header-border-bottom-color": v("primary-deep"),
    "--accent-color": v("link"),
    "--accent-color--major1": v("primary-deep"),
    "--accent-color--minor1": v("primary-light"),
    "--primary-button-color": v("action"),
    "--primary-button-color--major1": v("action-deep"),
    "--button--primary-background-color": v("action"),
    "--button--primary-background-hover-color": v("action-deep"),
    "--button--primary-border-color": v("action-deep"),
    "--button--primary-font-color": "#ffffff",
    "--button--background-color": "#ffffff",
    "--button--font-color": v("work-ink"),
    "--main-menu-bg-color": "#ffffff",
    "--main-menu-font-color": v("work-ink"),
    "--main-menu-selected-font-color": v("primary-deep"),
    "--main-menu-hover-font-color": v("work-ink"),
    "--main-menu-bg-selected-background": v("primary-light"),
    "--main-menu-bg-hover-background": v("work-soft"),
    "--main-menu-border-color": v("work-line"),
    "--main-menu-border-width": "1px",
    "--body-font-color": v("work-ink"),
    "--body-background": v("work-ground"),
    "--body-font-family": font,
    "--content-link-color": v("link"),
    # token aliases for the geometry part
    "--tt-primary": v("primary"),
    "--tt-primary-deep": v("primary-deep"),
    "--tt-primary-light": v("primary-light"),
    "--tt-action": v("action"),
    "--tt-action-deep": v("action-deep"),
    "--tt-ink": v("work-ink"),
    "--tt-muted": v("work-muted"),
    "--tt-line": v("work-line"),
    "--tt-field": v("work-field"),
    "--tt-ground": v("work-ground"),
    "--tt-soft": v("work-soft"),
    "--tt-link": v("link"),
    "--tt-radius": v("radius"),
    "--tt-radius-lg": v("radius-lg"),
    "--tt-font": font,
}
primer = {
    # Primer layer: defined on [data-color-mode], so :root alone does not reach it
    "--fgColor-default": v("work-ink"),
    "--fgColor-muted": v("work-muted"),
    "--fgColor-accent": v("link"),
    "--bgColor-accent-emphasis": v("primary"),
    "--borderColor-default": v("work-field"),
    "--borderColor-accent-emphasis": v("primary"),
    "--focus-outlineColor": v("primary"),
    "--control-borderColor-rest": v("work-field"),
    "--control-checked-bgColor-rest": v("primary"),
    "--button-primary-bgColor-rest": v("action"),
    "--button-primary-bgColor-hover": v("action-deep"),
    "--button-primary-borderColor-rest": v("action-deep"),
    "--button-default-bgColor-rest": "#ffffff",
    "--button-default-borderColor-rest": v("work-field"),
    "--borderRadius-medium": v("radius-lg"),
    "--fontStack-system": font,
    "--fontStack-sansSerif": font,
}

lines = [f"/* theme.css: generated by build-theme.py from token set '{system}'. Do not edit by hand. */",
         "", "/* 1. Token values on OpenProject's own variables */", ":root {"]
lines += [f"  {k}: {val};" for k, val in root.items()]
lines += ["}", "", "/* 1b. Token values on the Primer variables (light theme only in this spike) */",
          '[data-color-mode][data-light-theme="light"] {']
lines += [f"  {k}: {val};" for k, val in primer.items()]
lines += ["}", "", open(geometry).read()]
open(out, "w").write("\n".join(lines))
print(f"wrote {out}: {len(root)} root vars, {len(primer)} primer vars")
